final GlobalKey<NavigatorState> navigatorKey = GlobalKey<NavigatorState>();

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const CompanyProductsApp());
}

class CompanyProductsApp extends StatelessWidget {
  const CompanyProductsApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: appName,
      debugShowCheckedModeBanner: false,
      navigatorKey: navigatorKey,
      theme: ThemeData(
        useMaterial3: true,
        colorSchemeSeed: BrandColors.plum,
        inputDecorationTheme: const InputDecorationTheme(
          border: OutlineInputBorder(),
        ),
      ),
      // Session sits above the Navigator so every screen can read the signed-in user.
      builder: (context, child) => ValueListenableBuilder<AppUser?>(
        valueListenable: currentUser,
        builder: (context, user, _) => Session(user: user, child: child ?? const SizedBox.shrink()),
      ),
      home: const AuthGate(),
    );
  }
}

/// Shows the sign-in screen, or the app once a valid, active profile is loaded.
class AuthGate extends StatefulWidget {
  const AuthGate({super.key});

  @override
  State<AuthGate> createState() => _AuthGateState();
}

class _AuthGateState extends State<AuthGate> {
  StreamSubscription<User?>? _authSub;
  StreamSubscription<AppUser?>? _profileSub;
  bool _authReady = false;
  User? _authUser;
  bool _profileLoaded = false;
  AppUser? _profile;
  Object? _error;
  bool _migrated = false;

  @override
  void initState() {
    super.initState();
    _authSub = FirebaseAuth.instance.authStateChanges().listen(_onAuth);
  }

  void _backToHome() => navigatorKey.currentState?.popUntil((r) => r.isFirst);

  void _onAuth(User? user) {
    _profileSub?.cancel();
    _profileSub = null;
    currentUser.value = null;
    if (user == null) _backToHome();
    setState(() {
      _authReady = true;
      _authUser = user;
      _profile = null;
      _profileLoaded = false;
      _error = null;
    });
    if (user == null) return;

    _profileSub = Auth.watchUser(user.uid).listen(
      (profile) {
        final ok = profile != null && profile.active;
        if (!ok) _backToHome();
        currentUser.value = ok ? profile : null;
        // Once per app start, an admin moves any old single prices into the admin-only price store.
        if (ok && profile != null && profile.isAdmin && !_migrated) {
          _migrated = true;
          Db.migrateLegacyPrices().catchError((Object _) => 0);
        }
        if (mounted) {
          setState(() {
            _profile = profile;
            _profileLoaded = true;
            _error = null;
          });
        }
      },
      onError: (Object e) {
        currentUser.value = null;
        if (mounted) setState(() => _error = e);
      },
    );
  }

  @override
  void dispose() {
    _authSub?.cancel();
    _profileSub?.cancel();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    if (!_authReady) return const _Splash();
    if (_authUser == null) return const LoginScreen();
    if (_error != null) {
      return _Message(
        icon: Icons.error_outline,
        title: 'Could not load your account',
        text: '$_error',
      );
    }
    if (!_profileLoaded) return const _Splash();
    final profile = _profile;
    if (profile == null) {
      return const _Message(
        icon: Icons.hourglass_empty,
        title: 'Setting up your account…',
        text: 'If this doesn’t go away, this login has no profile. Ask an admin to add you.',
      );
    }
    if (!profile.active) {
      return const _Message(
        icon: Icons.block,
        title: 'Account disabled',
        text: 'Your account has been disabled. Please contact an admin.',
      );
    }
    return const CompaniesScreen();
  }
}

class _Splash extends StatelessWidget {
  const _Splash();
  @override
  Widget build(BuildContext context) => const Scaffold(body: Center(child: CircularProgressIndicator()));
}

class _Message extends StatelessWidget {
  final IconData icon;
  final String title;
  final String text;
  const _Message({required this.icon, required this.title, required this.text});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: SafeArea(
        child: Center(
          child: Padding(
            padding: const EdgeInsets.all(24),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                Icon(icon, size: 48),
                const SizedBox(height: 12),
                Text(title, style: Theme.of(context).textTheme.titleLarge, textAlign: TextAlign.center),
                const SizedBox(height: 8),
                Text(text, textAlign: TextAlign.center),
                const SizedBox(height: 24),
                OutlinedButton.icon(
                  onPressed: Auth.signOut,
                  icon: const Icon(Icons.logout),
                  label: const Text('Sign out'),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }
}
